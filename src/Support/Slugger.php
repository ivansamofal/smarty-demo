<?php

declare(strict_types=1);

namespace App\Support;

final class Slugger
{
    private const TRANSLITERATION_MAP = [
        'а' => 'a', 'б' => 'b', 'в' => 'v', 'г' => 'g', 'д' => 'd',
        'е' => 'e', 'ё' => 'e', 'ж' => 'zh', 'з' => 'z', 'и' => 'i',
        'й' => 'y', 'к' => 'k', 'л' => 'l', 'м' => 'm', 'н' => 'n',
        'о' => 'o', 'п' => 'p', 'р' => 'r', 'с' => 's', 'т' => 't',
        'у' => 'u', 'ф' => 'f', 'х' => 'h', 'ц' => 'ts', 'ч' => 'ch',
        'ш' => 'sh', 'щ' => 'sch', 'ъ' => '', 'ы' => 'y', 'ь' => '',
        'э' => 'e', 'ю' => 'yu', 'я' => 'ya',
    ];

    public static function slugify(string $value): string
    {
        $transliterated = strtr(mb_strtolower($value), self::TRANSLITERATION_MAP);
        $slug = trim((string) preg_replace('/[^a-z0-9]+/', '-', $transliterated), '-');

        return $slug !== '' ? $slug : 'item';
    }
}
